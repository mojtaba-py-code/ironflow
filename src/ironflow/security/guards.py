"""Input guards applied at every trust boundary.

A pipeline specification is *configuration*, but in a large organisation it is
frequently authored by someone other than the platform owner and may be
generated by an upstream system.  It is therefore treated as untrusted input:

``resolve_within``
    Confines every filesystem path to an allow-listed root, defeating
    ``../../etc/shadow`` and symlink escapes.
``validate_url`` / :class:`NetworkPolicy`
    Blocks SSRF: only ``http(s)``, no credentials in the URL, and by default no
    private/loopback address - including hosts that *resolve* to one.  The
    policy belongs to the operator: a pipeline can narrow it, never widen it.
    Resolving a name here is only a pre-flight check; the address a connection
    actually uses is re-checked at connect time by
    :mod:`ironflow.security.net`, which is what closes DNS rebinding.
``validate_identifier``
    SQL identifiers (table/column names) cannot be parameterised by the DB-API,
    so they must be validated against a strict pattern and quoted.  Values are
    always bound; identifiers are always validated.

These functions raise :class:`SecurityError` subclasses so a violation is
distinguishable from an ordinary configuration typo in metrics and alerts.
"""

from __future__ import annotations

import ipaddress
import re
import socket
from collections.abc import Iterable, Sequence
from dataclasses import dataclass, replace
from pathlib import Path
from typing import Any, Literal
from urllib.parse import urlparse, urlunparse

from ironflow.core.errors import ConfigurationError, SecurityError

#: Unquoted SQL identifiers: letter or underscore, then word characters.  Used
#: with ``fullmatch``: ``$`` alone also matches before a trailing newline, so
#: ``re.match`` let ``"orders\n"`` through.
_IDENTIFIER_RE = re.compile(r"[A-Za-z_][A-Za-z0-9_]{0,62}")
#: Optionally schema-qualified identifier.
_QUALIFIED_RE = re.compile(r"[A-Za-z_][A-Za-z0-9_]{0,62}(\.[A-Za-z_][A-Za-z0-9_]{0,62})?")

ALLOWED_URL_SCHEMES = frozenset({"http", "https"})

#: Screen for the raw ``where`` option.  Statement stacking, comments and set
#: operations change the statement's shape; the verbs write or reach outside the
#: predicate; the functions sleep (a query-level denial of service) or read and
#: write files on the database server.
_DANGEROUS_SQL = re.compile(
    r"(;|--|#|/\*|\*/"
    r"|\b(?:union|intersect|except|drop|delete|truncate|insert|update|merge|alter|create"
    r"|grant|revoke|exec|execute|call|copy|attach|detach|pragma|into)\b"
    r"|\bxp_|\bsp_"
    r"|\b(?:pg_sleep|sleep|benchmark|waitfor|load_file|pg_read_file|pg_read_binary_file"
    r"|pg_ls_dir|lo_import|lo_export|dblink|outfile|dumpfile)\b)",
    re.IGNORECASE,
)

IPAddress = ipaddress.IPv4Address | ipaddress.IPv6Address


# --------------------------------------------------------------------------- #
# Filesystem
# --------------------------------------------------------------------------- #
def resolve_within(
    path: str | Path, roots: Sequence[str | Path], *, must_exist: bool = False
) -> Path:
    """Resolve ``path`` and assert it stays inside one of ``roots``.

    ``Path.resolve`` collapses ``..`` *and* follows symlinks, so the comparison
    happens on the real target.  Checking the string before resolution - the
    common mistake - is bypassed by a symlink inside an allowed directory.

    An empty ``roots`` sequence means "unrestricted"; callers that handle
    untrusted paths must always pass a root.
    """
    candidate = Path(path).expanduser()
    resolved = candidate.resolve()

    if roots:
        allowed = [Path(r).expanduser().resolve() for r in roots]
        if not any(_is_relative_to(resolved, root) for root in allowed):
            raise SecurityError(
                "path escapes the configured data roots",
                context={"path": str(resolved), "roots": [str(r) for r in allowed]},
            )

    if must_exist and not resolved.exists():
        raise ConfigurationError("path does not exist", context={"path": str(resolved)})
    return resolved


def _is_relative_to(path: Path, root: Path) -> bool:
    try:
        path.relative_to(root)
    except ValueError:
        return False
    return True


def safe_filename(name: str, *, fallback: str = "file") -> str:
    """Strip directory components and unsafe characters from a filename.

    Applied to names that arrive from remote systems (SFTP listings, HTTP
    ``Content-Disposition``) before they are joined to a local directory.
    """
    stem = Path(name).name
    cleaned = re.sub(r"[^A-Za-z0-9._-]", "_", stem).lstrip(".")
    return cleaned[:200] or fallback


